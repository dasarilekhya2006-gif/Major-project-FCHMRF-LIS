"""Data schemas, metadata models, and validation contracts for neuroimaging volumes."""

from dataclasses import dataclass, field, asdict
from typing import Any, Dict, List, Optional, Tuple
import numpy as np


@dataclass
class NeuroimagingMetadata:
    """Detailed structural and header metadata extracted from a neuroimaging volume.

    Attributes:
        dimensions: Tuple of array dimensions (e.g., (X, Y, Z) or (X, Y, Z, T)).
        voxel_dimensions: Physical voxel spacing in millimeters (dx, dy, dz[, dt]).
        affine: 4x4 coordinate transformation matrix from voxel indices to world space.
        data_dtype: String representation of the underlying data type.
        ndim: Dimensionality of the volume (3 or 4).
        num_voxels: Total number of voxel elements.
        min_value: Minimum finite intensity value.
        max_value: Maximum finite intensity value.
        mean_value: Mean intensity value across all valid voxels.
        std_value: Standard deviation of intensity values.
        has_nan: True if the volume contains any NaN values.
        has_inf: True if the volume contains any infinite values.
        is_empty: True if the volume contains no signal or is uniformly zero.
        qform_code: NIfTI qform coordinate system code.
        sform_code: NIfTI sform coordinate system code.
        orientation: Canonical orientation string (e.g., 'RAS+', 'LPI-').
        description: Informational description string from NIfTI header.
        raw_header: Extracted dictionary of key NIfTI header fields.
    """

    dimensions: Tuple[int, ...]
    voxel_dimensions: Tuple[float, ...]
    affine: np.ndarray
    data_dtype: str
    ndim: int
    num_voxels: int
    min_value: float
    max_value: float
    mean_value: float
    std_value: float
    has_nan: bool
    has_inf: bool
    is_empty: bool
    qform_code: int = 0
    sform_code: int = 0
    orientation: str = "RAS+"
    description: str = ""
    raw_header: Dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> Dict[str, Any]:
        """Convert metadata to a serializable dictionary."""
        d = asdict(self)
        d["affine"] = self.affine.tolist()
        return d


@dataclass
class ValidationReport:
    """Report generated by image validation checks.

    Attributes:
        is_valid: Boolean indicating whether the volume satisfies all structural criteria.
        errors: List of critical validation error descriptions.
        warnings: List of non-fatal warnings (e.g., slight non-orthogonality).
        file_path: Optional path to the examined file.
        metadata: Extracted NeuroimagingMetadata if reading succeeded.
    """

    is_valid: bool
    errors: List[str] = field(default_factory=list)
    warnings: List[str] = field(default_factory=list)
    file_path: Optional[str] = None
    metadata: Optional[NeuroimagingMetadata] = None

    def add_error(self, message: str) -> None:
        self.errors.append(message)
        self.is_valid = False

    def add_warning(self, message: str) -> None:
        self.warnings.append(message)


@dataclass
class NeuroimagingVolume:
    """Represents a normalized 3D or 4D neuroimaging volume in memory.

    Attributes:
        data: NumPy ndarray of intensity/statistical values (float32).
        affine: 4x4 coordinate affine transformation matrix.
        voxel_dimensions: Physical size of voxels in mm (dx, dy, dz[, dt]).
        mask: Optional binary spatial mask of shape (nx, ny, nz).
        subject_id: Optional identifier for subject, session, or contrast name.
        metadata: Extracted NeuroimagingMetadata.
    """

    data: np.ndarray
    affine: np.ndarray = field(default_factory=lambda: np.eye(4, dtype=np.float32))
    voxel_dimensions: Tuple[float, ...] = (2.0, 2.0, 2.0)
    mask: Optional[np.ndarray] = None
    subject_id: Optional[str] = None
    metadata: Optional[NeuroimagingMetadata] = None

    def __post_init__(self) -> None:
        if self.data.ndim not in (3, 4):
            raise ValueError(
                f"NeuroimagingVolume requires 3D or 4D array, received ndim={self.data.ndim} (shape {self.data.shape})"
            )

        # Enforce float32 representation internally
        if self.data.dtype != np.float32:
            self.data = self.data.astype(np.float32)

        # Validate mask matching spatial dimensions
        if self.mask is not None:
            spatial_shape = self.data.shape[:3]
            if self.mask.shape != spatial_shape:
                raise ValueError(
                    f"Mask shape {self.mask.shape} does not match spatial shape {spatial_shape}"
                )
            if self.mask.dtype != bool:
                self.mask = self.mask.astype(bool)

    @property
    def is_3d(self) -> bool:
        """True if the volume is a 3D spatial field."""
        return self.data.ndim == 3

    @property
    def is_4d(self) -> bool:
        """True if the volume is a 4D spatio-temporal volume."""
        return self.data.ndim == 4

    @property
    def shape(self) -> Tuple[int, ...]:
        """Full dimensions of the volume."""
        return self.data.shape

    @property
    def spatial_shape(self) -> Tuple[int, int, int]:
        """Spatial dimensions (nx, ny, nz)."""
        return self.data.shape[0], self.data.shape[1], self.data.shape[2]

    @property
    def voxel_spacing(self) -> Tuple[float, ...]:
        """Physical spacing of voxels in mm (alias for voxel_dimensions)."""
        return self.voxel_dimensions

    @property
    def num_timepoints(self) -> int:
        """Number of temporal volumes (1 if 3D)."""
        return self.data.shape[3] if self.is_4d else 1

    @property
    def num_voxels(self) -> int:
        """Total number of voxel elements across all dimensions."""
        return int(np.prod(self.data.shape))

    @property
    def num_spatial_voxels(self) -> int:
        """Total number of voxels in the 3D spatial grid."""
        return int(np.prod(self.spatial_shape))

    @property
    def num_brain_voxels(self) -> int:
        """Total number of in-mask spatial voxels."""
        if self.mask is not None:
            return int(np.sum(self.mask))
        return self.num_spatial_voxels

    def to_3d(self, time_index: int = 0) -> "NeuroimagingVolume":
        """Extract a single 3D volume from a 4D timeseries.

        Args:
            time_index: Zero-based index along the 4th dimension.

        Returns:
            NeuroimagingVolume: 3D volume slice.
        """
        if self.is_3d:
            return self

        if time_index < 0 or time_index >= self.shape[3]:
            raise IndexError(
                f"Time index {time_index} out of bounds for 4D volume with {self.shape[3]} timepoints."
            )

        data_3d = self.data[..., time_index].copy()
        voxel_dims_3d = tuple(self.voxel_dimensions[:3])
        return NeuroimagingVolume(
            data=data_3d,
            affine=self.affine.copy(),
            voxel_dimensions=voxel_dims_3d,
            mask=self.mask.copy() if self.mask is not None else None,
            subject_id=self.subject_id,
            metadata=self.metadata,
        )

    def mean_across_time(self) -> "NeuroimagingVolume":
        """Compute the temporal mean of a 4D timeseries to produce a 3D summary volume."""
        if self.is_3d:
            return self

        mean_data = np.mean(self.data, axis=-1, dtype=np.float32)
        voxel_dims_3d = tuple(self.voxel_dimensions[:3])
        return NeuroimagingVolume(
            data=mean_data,
            affine=self.affine.copy(),
            voxel_dimensions=voxel_dims_3d,
            mask=self.mask.copy() if self.mask is not None else None,
            subject_id=self.subject_id,
            metadata=self.metadata,
        )


@dataclass
class SyntheticBenchmarkSample:
    """Container for synthetic spatial data with known ground truth activations.

    Attributes:
        z_map: Observed 3D z-score map.
        ground_truth: Binary 3D mask where 1 indicates true activation, 0 indicates null.
        noise_field: 3D background noise realization before signal injection.
        snr: Signal-to-noise ratio used during generation.
        cluster_centers: List of 3D coordinates for synthetic activation clusters.
    """

    z_map: np.ndarray
    ground_truth: np.ndarray
    noise_field: np.ndarray
    snr: float
    cluster_centers: List[Tuple[int, int, int]] = field(default_factory=list)
